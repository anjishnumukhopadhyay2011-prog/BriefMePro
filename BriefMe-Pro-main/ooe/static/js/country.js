function isEventInNativeCountry(event) {
  if (!state.nativeCountry) return true;
  const country = state.nativeCountry;
  const eventText = [
    event.country || "",
    event.region || "",
    event.location_name || "",
    event.title || "",
    event.summary || "",
  ].join(" ").toLowerCase();

  // Check direct country name match
  if (eventText.includes(country.name.toLowerCase())) return true;

  // Check aliases
  for (const alias of (country.aliases || [])) {
    if (eventText.includes(alias.toLowerCase())) return true;
  }

  // Check reverse: event country matches any of our known aliases for this country
  const evCountry = (event.country || "").trim();
  const evRegion = (event.region || "").trim();
  const knownAliases = COUNTRY_ALIASES[country.name] || country.aliases || [];
  for (const a of knownAliases) {
    if (evCountry.toLowerCase() === a.toLowerCase() || evRegion.toLowerCase().includes(a.toLowerCase())) return true;
  }

  return false;
}
